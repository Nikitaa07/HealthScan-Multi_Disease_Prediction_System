import pandas as pd
import numpy as np
import joblib

from sklearn.model_selection import train_test_split, StratifiedKFold, cross_validate
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.impute import SimpleImputer

from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report
)

"""2. Load Datset

"""

data = pd.read_csv("heart_dataset.csv")

print("Dataset Loaded Successfully!")
print("Dataset Shape:", data.shape)
print("\nFirst 5 Records:")
print(data.head())

"""3. Collection and Basic Information"""

print("\nDataset Information:")
print(data.info())

print("\nMissing Values:")
print(data.isnull().sum())

print("\nDuplicate Records:", data.duplicated().sum())

"""4. Data Cleaning"""

# Remove duplicate records
data = data.drop_duplicates()

# Remove rows where target value is missing
data = data.dropna(subset=["HeartDisease"])

# In this dataset, 0 in these columns represents missing measurement
data["RestingBP"] = data["RestingBP"].replace(0, np.nan)
data["Cholesterol"] = data["Cholesterol"].replace(0, np.nan)

print("\nAfter Cleaning:")
print("Dataset Shape:", data.shape)
print("Missing Values:")
print(data.isnull().sum().sum())

"""5. Feature Selection"""

# Input features
features = [
    "Age",
    "Sex",
    "ChestPainType",
    "RestingBP",
    "FastingBS",
    "MaxHR",
    "ExerciseAngina",
    "ST_Slope"
]

# Target column
target = "HeartDisease"

X = data[features]
y = data[target]

print("\nSelected Features:")
print(features)

print("\nTarget Variable:", target)

"""6. Separate Numerical and Categorical Features"""

numeric_features = [
    "Age",
    "RestingBP",
    "FastingBS",
    "MaxHR"
]

categorical_features = [
    "Sex",
    "ChestPainType",
    "ExerciseAngina",
    "ST_Slope"
]

"""7. Preprocessing"""

# Numerical data: Fill missing values and scale
numeric_preprocessing = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

# Categorical data: Fill missing values and encode
categorical_preprocessing = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

# Combine both preprocessing steps
preprocessor = ColumnTransformer([
    ("numeric", numeric_preprocessing, numeric_features),
    ("categorical", categorical_preprocessing, categorical_features)
])

print("\nPreprocessing Completed!")

"""8. Train-Test Split"""

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("\nData Splitting Completed!")
print("Training Records:", X_train.shape[0])
print("Testing Records:", X_test.shape[0])

"""9. Create Three Machine Learning Models"""

models = {
    "Logistic Regression": LogisticRegression(max_iter=2000),

    "Decision Tree": DecisionTreeClassifier(
        max_depth=4,
        min_samples_leaf=4,
        random_state=42
    ),

    "Random Forest": RandomForestClassifier(
        n_estimators=300,
        min_samples_leaf=3,
        random_state=42
    )
}

"""10. Cross Validation and Model Comparison"""

cross_validation = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

results = []
trained_models = {}

for model_name, algorithm in models.items():

    model_pipeline = Pipeline([
        ("preprocessing", preprocessor),
        ("model", algorithm)
    ])

    # Calculate all four metrics using 5-fold cross validation
    scores = cross_validate(
        model_pipeline,
        X_train,
        y_train,
        cv=cross_validation,
        scoring=["accuracy", "precision", "recall", "f1"]
    )

    # Calculate average scores
    avg_accuracy = scores["test_accuracy"].mean()
    avg_precision = scores["test_precision"].mean()
    avg_recall = scores["test_recall"].mean()
    avg_f1 = scores["test_f1"].mean()

    # Train model on complete training data
    model_pipeline.fit(X_train, y_train)

    trained_models[model_name] = model_pipeline

    # Store results
    results.append({
        "Model": model_name,
        "Accuracy": avg_accuracy,
        "Precision": avg_precision,
        "Recall": avg_recall,
        "F1 Score": avg_f1
    })

    # Print individual model performance
    print("\n==========", model_name, "==========")
    print("Accuracy :", round(avg_accuracy * 100, 2), "%")
    print("Precision:", round(avg_precision * 100, 2), "%")
    print("Recall   :", round(avg_recall * 100, 2), "%")
    print("F1 Score :", round(avg_f1 * 100, 2), "%")

"""11. Compare Models"""

# 11. Compare Models

results_df = pd.DataFrame(results)

print("\n========== MODEL COMPARISON ==========")
print(results_df.round(3).to_string(index=False))

"""12. Select Best Model"""

# 12. Select Best Model

results_df = results_df.sort_values(
    by="Recall",
    ascending=False
)

best_model_name = results_df.iloc[0]["Model"]

best_model = trained_models[best_model_name]

print("\n========== BEST MODEL ==========")
print("Best Model Selected:", best_model_name)
print("Best Model Recall:",
      round(results_df.iloc[0]["Recall"] * 100, 2), "%")

"""13. Test the Best Model"""

predictions = best_model.predict(X_test)

accuracy = accuracy_score(y_test, predictions)
precision = precision_score(y_test, predictions, zero_division=0)
recall = recall_score(y_test, predictions, zero_division=0)
f1 = f1_score(y_test, predictions, zero_division=0)

print("\n========== FINAL MODEL PERFORMANCE ==========")

print("Accuracy :", round(accuracy * 100, 2), "%")
print("Precision:", round(precision * 100, 2), "%")
print("Recall   :", round(recall * 100, 2), "%")
print("F1 Score :", round(f1 * 100, 2), "%")

"""14. Confusion Matrix"""

matrix = confusion_matrix(y_test, predictions, labels=[0, 1])

print("\n========== CONFUSION MATRIX ==========")
print("             Predicted")
print("             0       1")
print("Actual  0   ", matrix[0][0], "    ", matrix[0][1])
print("        1   ", matrix[1][0], "    ", matrix[1][1])

print("\nClassification Report:")
print(classification_report(y_test, predictions, zero_division=0))

"""15. Train Final Model on Complete Dataset"""

best_model.fit(X, y)

# Save the trained model
joblib.dump(best_model, "heart_model.pkl")

print("\nFinal Model Trained Successfully!")
print("Model Saved as heart_model.pkl")

"""16. Take New Patient Details and Predict"""

print("\n========== HEART DISEASE PREDICTION ==========")

age = int(input("Enter Age: "))
sex = input("Enter Sex (M/F): ")
chest_pain = input("Enter Chest Pain Type (TA/ATA/NAP/ASY): ")

resting_bp = float(input("Enter Resting Blood Pressure: "))

fasting_bs = int(input("Enter Fasting Blood Sugar (0/1): "))

max_hr = float(input("Enter Maximum Heart Rate: "))
exercise_angina = input("Enter Exercise Angina (Y/N): ")

st_slope = input("Enter ST Slope (Up/Flat/Down): ")


# Store input in DataFrame
new_patient = pd.DataFrame([{
    "Age": age,
    "Sex": sex,
    "ChestPainType": chest_pain,
    "RestingBP": resting_bp,
    "FastingBS": fasting_bs,
    "MaxHR": max_hr,
    "ExerciseAngina": exercise_angina,
    "ST_Slope": st_slope
}])

# Make prediction
result = best_model.predict(new_patient)

print("\nPrediction Result:")

if result[0] == 1:
    print("Heart Disease: Positive\n Risk Of heart disease")
else:
    print("Heart Disease: Negative\n No risk of heart disease")